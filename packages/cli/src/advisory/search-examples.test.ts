import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { expect, it } from 'vitest';
import { runCli } from '../cli.js';
const directory=new URL('../../fixtures/advisory/search/',import.meta.url);
it('keeps complete, no-match and scope guidance examples generated by the real local CLI',async()=>{
 const cases=JSON.parse(await readFile(new URL('examples.json',directory),'utf8')) as {name:string;question:string;status:string}[];
 const input=fileURLToPath(new URL('../../fixtures/advisory/complete/',import.meta.url));
 for(const example of cases){
  for(const format of ['json','markdown'] as const){
   const output:string[]=[];expect(await runCli(['advisory','ask','--input',input,'--question',example.question,'--format',format],{stdout:s=>output.push(s),stderr:s=>output.push(s)})).toBe(0);
   const expected=await readFile(new URL(example.name+(format==='json'?'.json':'.md'),directory),'utf8');
   expect(output.join('')).toBe(expected);
   if(format==='json')expect(JSON.parse(expected).status).toBe(example.status);
  }
 }
});
